namespace Isekai.Engine.Diagnostics;

/// <summary>
/// Defines log levels used by the engine diagnostics system.
/// </summary>
public static class EngineLogLevels
{
    /// <summary>
    /// Disables diagnostic output.
    /// </summary>
    public const int Off = 0;

    /// <summary>
    /// Enables full function entry and exit tracing.
    /// </summary>
    public const int FullTrace = 10;
}
